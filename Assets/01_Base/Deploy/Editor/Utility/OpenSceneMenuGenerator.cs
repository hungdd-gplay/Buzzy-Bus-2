using System.IO;
using System.Text;
using UnityEditor;
using UnityEditor.SceneManagement;
using UnityEngine;

/// <summary>
/// Tự sinh menu "Open Scene" theo đúng thứ tự Scene List trong Build Profile / Build Settings.
/// - Scene thứ 1..9 có phím tắt Alt+1..Alt+9 (Unity chỉ hỗ trợ 1 phím số, scene thứ 10 trở đi không có phím tắt).
/// - Tự sinh lại khi Scene List thay đổi (thêm / xoá / đổi thứ tự).
/// - Mở scene theo GUID nên đổi tên / di chuyển scene vẫn mở đúng.
/// File sinh ra: OpenSceneMenu.Generated.cs (cùng thư mục) - KHÔNG sửa tay.
/// </summary>
[InitializeOnLoad]
public static class OpenSceneMenuGenerator
{
    private const string _MENU_ROOT = "Open Scene/";
    private const string _GENERATED_FILE_NAME = "OpenSceneMenu.Generated.cs";
    private const int _MAX_SHORTCUT = 9;

    static OpenSceneMenuGenerator()
    {
        EditorBuildSettings.sceneListChanged -= _OnSceneListChanged;
        EditorBuildSettings.sceneListChanged += _OnSceneListChanged;
        // Đồng bộ lần đầu (sau khi compile xong) nếu menu đang lệch với Scene List
        EditorApplication.delayCall += () => GenerateMenu(false);
    }

    private static void _OnSceneListChanged()
    {
        GenerateMenu(false);
    }

    [MenuItem(_MENU_ROOT + "Refresh Scene Menu", false, 1000)]
    public static void RefreshSceneMenu()
    {
        GenerateMenu(true);
    }

    /// <summary>Mở scene (hỏi lưu scene hiện tại nếu có thay đổi). Được gọi từ file Generated.</summary>
    public static void OpenSceneByGuid(string guidScene, string pathSceneFallback)
    {
        if (EditorApplication.isPlaying)
        {
            Debug.LogWarning("[OpenScene] Đang Play, hãy dừng Play trước khi đổi scene.");
            return;
        }
        string _path = AssetDatabase.GUIDToAssetPath(guidScene);
        if (string.IsNullOrEmpty(_path) || !File.Exists(_path))
            _path = pathSceneFallback;
        if (string.IsNullOrEmpty(_path) || !File.Exists(_path))
        {
            Debug.LogError($"[OpenScene] Không tìm thấy scene: {pathSceneFallback}. Hãy chạy 'Open Scene/Refresh Scene Menu'.");
            return;
        }
        if (EditorSceneManager.SaveCurrentModifiedScenesIfUserWantsTo())
            EditorSceneManager.OpenScene(_path);
    }

    public static void GenerateMenu(bool isForceLog)
    {
        string _filePath = _GetGeneratedFilePath();
        if (string.IsNullOrEmpty(_filePath))
            return;

        string _newContent = _BuildGeneratedContent();
        string _oldContent = File.Exists(_filePath) ? File.ReadAllText(_filePath) : string.Empty;
        if (_Normalize(_oldContent) == _Normalize(_newContent))
        {
            if (isForceLog)
                Debug.Log("[OpenScene] Menu đã khớp với Scene List, không cần sinh lại.");
            return;
        }

        File.WriteAllText(_filePath, _newContent, new UTF8Encoding(true));
        AssetDatabase.ImportAsset(_ToAssetPath(_filePath));
        Debug.Log($"[OpenScene] Đã sinh lại menu Open Scene ({EditorBuildSettings.scenes.Length} scene).");
    }

    private static string _BuildGeneratedContent()
    {
        var _scenes = EditorBuildSettings.scenes;
        var _sb = new StringBuilder();
        _sb.Append("// <auto-generated> File do OpenSceneMenuGenerator sinh ra từ Scene List. KHÔNG sửa tay. </auto-generated>\n");
        _sb.Append("using UnityEditor;\n\n");
        _sb.Append("public static class OpenSceneMenuGenerated\n{\n");
        for (int i = 0; i < _scenes.Length; i++)
        {
            int _order = i + 1;
            string _path = _scenes[i].path;
            string _guid = _scenes[i].guid.ToString();
            string _label = _EscapeMenuLabel(Path.GetFileNameWithoutExtension(_path));
            if (!_scenes[i].enabled)
                _label += " (disabled)";
            string _shortcut = _order <= _MAX_SHORTCUT ? " &" + _order : string.Empty;

            _sb.Append($"    [MenuItem(\"{_MENU_ROOT}{_label}{_shortcut}\", false, {_order})]\n");
            _sb.Append($"    private static void OpenScene_{_order}() {{ OpenSceneMenuGenerator.OpenSceneByGuid(\"{_guid}\", \"{_EscapeString(_path)}\"); }}\n\n");
        }
        _sb.Append("}\n");
        return _sb.ToString();
    }

    private static string _GetGeneratedFilePath()
    {
        // Đặt file Generated cạnh file generator này
        string[] _guids = AssetDatabase.FindAssets("OpenSceneMenuGenerator t:MonoScript");
        foreach (var _guid in _guids)
        {
            string _assetPath = AssetDatabase.GUIDToAssetPath(_guid);
            if (Path.GetFileName(_assetPath) == "OpenSceneMenuGenerator.cs")
                return Path.Combine(Path.GetDirectoryName(_assetPath), _GENERATED_FILE_NAME).Replace('\\', '/');
        }
        return null;
    }

    private static string _ToAssetPath(string filePath)
    {
        return filePath.Replace('\\', '/');
    }

    private static string _Normalize(string content)
    {
        return content.Replace("\r\n", "\n").Trim();
    }

    private static string _EscapeString(string value)
    {
        return value.Replace("\\", "\\\\").Replace("\"", "\\\"");
    }

    private static string _EscapeMenuLabel(string value)
    {
        // Ký tự %, #, &, _ ở cuối label bị Unity hiểu là phím tắt -> thay bằng khoảng trắng an toàn
        return _EscapeString(value.Replace("%", " ").Replace("#", " ").Replace("&", " "));
    }
}
